import math
from figlib import *

FIGS = {}


def fig(name):
    def deco(fn):
        FIGS[name] = fn
        return fn
    return deco


def P(d, fill="none", stroke=INK, sw=1.5, extra=""):
    return f'<path d="{d}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" stroke-linejoin="round" stroke-linecap="round" {extra}/>'


def poly(pts, fill):
    return f'<polygon points="{" ".join(f"{f(x)},{f(y)}" for x, y in pts)}" fill="{fill}"/>'


def tag(x, y, s, size=12.5, color=ACCENT):
    return label(x, y, s, size, color)


def lead(x1, y1, x2, y2, s, anchor="start", size=13, color=INK, sub=None):
    o = leader(x1, y1, x2, y2, s, anchor, size, color)
    if sub:
        dx = 4 if anchor == "start" else (-4 if anchor == "end" else 0)
        o += text(x2 + dx, y2 + 19, sub, 11, ACCENT, anchor, 700)
    return o


