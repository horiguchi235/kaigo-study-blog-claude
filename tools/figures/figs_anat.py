def spiral(cx, cy, r0, r1, turns, steps=120):
    pts = []
    for i in range(steps + 1):
        t = i / steps
        a = t * turns * 2 * math.pi
        rr = r0 + (r1 - r0) * t
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return "M" + " L".join(f"{f(x)},{f(y)}" for x, y in pts)


